def negative_sentences(text, closing_re, locks):
    """四段口径：全文里句首是否定词的句子，逐句列出（固定句、引号内台词、用户逐字锁不算）。
    切句前先去掉段落标题与镜头标题，紧跟标题的第一句（“主体：不要任何声音。”“镜头1（0-4秒）：不出现文字水印。”）同样算句首。"""
    t = strip_heads(strip_dialogue(text))
    for lk in sorted(locks, key=len, reverse=True):
        t = t.replace(lk, "")
    t = closing_re.sub("", t)
    out = []
    for raw in re.split(r"[。！？!?；;\n]", t):
        s = raw.strip()
        if s and NEG_SENT_RE.match(s):
            out.append(s)
    return out


def operation_text(text):
    """命令区：六段旧稿取概述段；四段新稿与五段旧稿取情节段开头到第一个镜头 / 阶段标题之前。"""
    m = re.search(r"概述[：:](.*?)(?=\n(?:主体|场景|风格|情节|结尾)[：:]|\Z)", text, re.S)
    if m:
        return m.group(1)
    m = re.search(r"情节[：:](.*?)(?=\n\s*(?:镜头\s*\d+|【阶段|第[" + CJK_NUM + r"\d]+阶段|\d+(?:\.\d+)?\s*(?:s|秒)?\s*[-–—~到]\s*\d+(?:\.\d+)?\s*(?:s|秒)\s*[:：])|\n(?:主体|场景|风格|结尾)[：:]|\Z)", text, re.S)
    if m:
        return m.group(1)
    # 兼容继承的无标题操作稿：只看第一个镜头 / 阶段之前的命令区，不让镜内叙事误判任务类型。
    prefix = []
    for line in text.splitlines():
        if any(rx.match(line) for rx in HEAD_PATTERNS.values()):
            break
        prefix.append(line)
    return "\n".join(prefix)


EXTEND_CMD_RE = re.compile(r"向后延长|向前延长|续写|延续\s*@?视频\s?\d")   # 延长的必填词：“延续”只认“延续视频N”
# 生成类四段稿情节段开头的命令区里，算操作或素材职责的句子不算总览句：句中有 视频N / 图N / 音频N / 宫格 / 首帧 / 尾帧 / 关键帧 /
# 参考 / 沿用 / 白模 / 绿幕 / 一键成片，或以“参考视频N的 / 作为首帧 / 提供宫格分镜 / 以图N”开头。词表可调
COMMAND_SENT_RE = re.compile(r"@?(?:视频|图片|图|音频)\s?\d|宫格|首帧|尾帧|关键帧|参考|沿用|白模|粗模|绿幕|一键成片|切点|逐帧|一致性"
                             r"|^\s*(?:参考@?视频\s?\d+的|作为首帧|提供宫格分镜|以@?图\s?\d)")
EDIT_VERB = r"(?:编辑|替换|删除|增加|移除|去掉)"
# 编辑：动词紧挨着视频N（编辑视频1、删除@视频2），或“视频N中 / 里 / 的……替换 / 删除……”同一分句里；
# “参考视频1的运镜，光亮逐渐增加”这种分句被逗号隔开的不算，镜内的“雨势增加”不在命令区里
EDIT_CMD_RE = re.compile(EDIT_VERB + r"\s*@?视频\s?\d|@?视频\s?\d+\s*(?:中|里|的)[^，,。；;！!？?\n]{0,15}?" + EDIT_VERB)


def infer_task_from_text(text):
    """按命令区推断任务类型（六段旧稿看概述段，四段与五段看情节段开头到第一个镜头 / 阶段标题之前）：
    向后延长 / 向前延长 / 续写 / 延续视频N → 延长；编辑 / 替换 / 删除 / 增加 / 移除紧挨着视频N → 编辑；无缝衔接 → 衔接；否则生成。
    check_prompt 没给 --task、旧写法 --task 修订（按父稿推断）与 hooks/stop_gate.py 代跑共用这一个函数。"""
    ov = operation_text(text)
    if EXTEND_CMD_RE.search(ov):
        return "延长"
    if EDIT_CMD_RE.search(ov):
        return "编辑"
    if "无缝衔接" in ov or "衔接起来" in ov:
        return "衔接"
    return "生成"


def infer_task(baseline_text):
    """旧写法 --task 修订：按父稿的命令区推断。"""
    return infer_task_from_text(baseline_text)


