def synthesize(baseline_lines, cand_lines, errors, unchanged_ids, baseline_fmt=None):
    """校验局部替换段，再放回父稿。返回合成后的行列表。"""
    b_heads = parse_heads(baseline_lines)
    c_heads = parse_heads(cand_lines)
    if not c_heads:
        errors.append("局部替换段里没有找到镜头标题")
        return baseline_lines
    pre = "".join(cand_lines[:c_heads[0][0]]).strip()
    if pre:
        errors.append(f"局部替换段开头有无法归属的文字，不能静默丢弃：{pre[:40]}")
    c_ids = [h[2] for h in c_heads]
    if any(i is None for i in c_ids):
        errors.append("局部替换段的镜头标题没有镜号，无法定位到父稿")
        return baseline_lines
    dup = sorted({i for i in c_ids if c_ids.count(i) > 1})
    if dup:
        errors.append(f"局部替换段里镜号重复：{dup}")
    c_blocks = shot_blocks(cand_lines, c_heads, len(cand_lines) if baseline_fmt == "四段" else None)
    for h, _body, tail in c_blocks:
        if "".join(tail).strip():
            errors.append(f"局部镜头 {h[2]} 后有固定句或收尾行，不能丢弃；收尾有改动请交付全稿")
    for sid in c_ids:
        if sid in unchanged_ids:
            errors.append(f"镜头 {sid} 被标为未改（--unchanged），局部替换段却改了它")
    b_ids = {h[2]: h for h in b_heads if h[2] is not None}
    b_blocks = shot_blocks(baseline_lines, b_heads, len(baseline_lines) if baseline_fmt == "四段" else None)
    repl = {}
    for (h, body, _tail) in c_blocks:
        sid = h[2]
        if sid not in b_ids:
            errors.append(f"局部替换的镜头 {sid} 不在父稿里")
            continue
        bh = b_ids[sid]
        if h[3] is not None and bh[3] is not None and (abs(h[3] - bh[3]) > 1e-6 or abs(h[4] - bh[4]) > 1e-6):
            errors.append(f"镜头 {sid} 的时码 {h[3]}-{h[4]} 与父稿 {bh[3]}-{bh[4]} 不一致；改时码要先改父稿总时长并交付全稿")
        repl[sid] = body
    out = []
    first = b_heads[0][0] if b_heads else len(baseline_lines)
    out.extend(baseline_lines[:first])
    for (h, body, tail) in b_blocks:
        out.extend(repl.get(h[2], body))
        out.extend(tail)
    return out


def parse_asks(path):
    """要求清单：一行一条 `编号 | 时间 | 用户原话摘录 | 落点关键词 | 状态`，`#` 开头是注释。
    关键词列自己也用 `|` 分同义词，所以切列口径是"前三列 + 最后一列固定，中间全部归关键词列"。
    返回 (条目列表, 格式错误列表)。"""
    rows, errs, seen = [], [], {}
    for no, raw in enumerate(Path(path).read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 5:
            errs.append(f"要求清单第 {no} 行列数不对，应为 5 列「编号 | 用户提出时间 | 用户原话摘录 | 落点关键词 | 状态」："
                        f"{line[:40]}")
            continue
        rid, when, quote, status = parts[0], parts[1], parts[2], parts[-1]
        keys = "|".join(parts[3:-1])
        if status.startswith("有效"):
            active = True
        elif status.startswith("撤回"):
            active = False
        else:
            errs.append(f"要求清单第 {no} 行状态不是「有效」或「撤回（时间＋用户原话）」：{status[:40]}")
            continue
        if not rid or not quote:
            errs.append(f"要求清单第 {no} 行缺编号或用户原话摘录：{line[:40]}")
            continue
        if rid in seen:
            errs.append(f"要求清单编号重复：{rid} 出现在第 {seen[rid]} 行和第 {no} 行")
            continue
        seen[rid] = no
        groups = [[w.strip() for w in g.split("|") if w.strip()] for g in re.split(r"[；;]", keys) if g.strip()]
        if active and not groups:
            errs.append(f"要求清单第 {no} 行「{rid}」是有效状态却没有写落点关键词")
            continue
        rows.append({"id": rid, "when": when, "quote": quote, "groups": groups, "active": active, "status": status})
    return rows, errs


def ask_excerpt(quote, limit=20):
    """错误里引用用户原话的头一句，最多 limit 字；截断了就加省略号。"""
    q = quote.strip()
    head = re.split(r"[，,。.；;！!？?、]", q)[0][:limit]
    return head + "……" if head != q else head


def split_sentences(text):
    """按句号、分号、问号、感叹号和换行切句；引号内不切。返回原文句子（去首尾空白，空句丢弃）。"""
    out, buf, closer = [], [], None
    for ch in text:
        if closer is not None:
            buf.append(ch)
            if ch == closer:
                closer = None
            continue
        if ch in QUOTE_OPEN:
            closer = QUOTE_OPEN[ch]
            buf.append(ch)
            continue
        if ch in SENT_END or ch == "\n":
            s = "".join(buf).strip()
            if s:
                out.append(s)
            buf = []
            continue
        buf.append(ch)
    s = "".join(buf).strip()
    if s:
        out.append(s)
    return out


def sentence_regions(text):
    """按全局段落、镜号与尾部隔离；不让另一镜的相似句顶替本镜要求。"""
    lines = text.splitlines()
    heads = {h[0]: h for h in parse_heads(lines)}
    regions, key = {}, ("global", "prefix")
    for i, line in enumerate(lines):
        if i in heads:
            h = heads[i]
            key = ("shot", h[2] if h[2] is not None else (h[3], h[4]))
        elif is_tail_line(line):
            key = ("global", "tail")
        else:
            match = KNOWN_HEADER.match(line)
            if match:
                key = ("global", match.group(1))
        regions.setdefault(key, []).append(line)
    return {key: split_sentences("\n".join(lines)) for key, lines in regions.items()}


def lost_sentences(old_text, new_text):
    """逐镜先精确、再相似地一对一匹配；未匹配旧句只作提醒。"""
    old_regions, new_regions = sentence_regions(old_text), sentence_regions(new_text)
    lost = []
    for key, old in old_regions.items():
        new = new_regions.get(key, [])
        old_norm = [re.sub(r"\s+", "", s) for s in old]
        new_norm = [re.sub(r"\s+", "", s) for s in new]
        remaining_old, remaining_new = set(range(len(old))), set(range(len(new)))
        # 先占用完全保留的句子，不能再拿它替代被删掉的相近旧句。
        for i, n in enumerate(old_norm):
            match = next((j for j in sorted(remaining_new) if n == new_norm[j]), None)
            if match is not None:
                remaining_old.remove(i)
                remaining_new.remove(match)
        pairs = sorted(
            ((difflib.SequenceMatcher(None, old_norm[i], new_norm[j]).ratio(), i, j)
             for i in remaining_old for j in remaining_new), reverse=True)
        for similarity, i, j in pairs:
            if similarity < SENT_SIMILAR:
                break
            if i in remaining_old and j in remaining_new:
                remaining_old.remove(i)
                remaining_new.remove(j)
        lost.extend(old[i] for i in sorted(remaining_old))
    return lost


def nonspace_len(text):
    return len(re.sub(r"\s", "", text))


def strip_heads(text):
    """逐行去掉镜头标题与段落标题前缀（镜头1（0-3秒）：/ 主体：……），留下正文。"""
    lines = []
    for ln in text.splitlines():
        m = next((m for rx in HEAD_PATTERNS.values() for m in [rx.match(ln)] if m), None)
        ln = ln[m.end():] if m else ln
        lines.append(re.sub(r"^\s*(?:主体|场景|风格|情节|概述|结尾)[：:]", "", ln))
    return "\n".join(lines)


def void_hits(text):
    """要报的绝对化空或黑词。VOID_INTENT_WORDS 里的词每一处所在句都写明了持续多久或占多大范围时，算有意的纯黑，不报；
    先挖掉镜头标题（时码不算时长）和“不采用……”排除分句（不采用图中的纯黑背景说的是参考图，不是画面）。"""
    body = "\n".join(SUBJECT_SKIP_RE.sub("", ln) for ln in strip_heads(text).splitlines())
    sents = split_sentences(body)
    out = []
    for w in ABSOLUTE_VOID_WORDS:
        hit = [s for s in sents if w in s]
        if hit and not (w in VOID_INTENT_WORDS and all(VOID_INTENT_RE.search(s) for s in hit)):
            out.append(w)
    return out


def micro_scale_hits(body):
    """镜头正文（已去掉台词）里要报的尺度名词：取它前面最近的景别词或画框切线（被“不是 / 并非 / 不……”否定的不算），
    同镜内往前找，前面一个都没有就看同一句后面；是特写 / 大特写 / 微距才不报，没有任何取景线索也报。"""
    marks = [(m.start(), m.group(0)) for m in SCALE_MARK_RE.finditer(body)
             if not SCALE_NEGATION_RE.search(body[max(0, m.start() - 3):m.start()])]
    out = []
    for w in MICRO_SCALE_WORDS:
        for m in re.finditer(w, body):
            before = [g for p, g in marks if p < m.start()]
            if before:
                g = before[-1]
            else:
                end = min([i for i in (body.find(c, m.end()) for c in "。；;！!？?\n") if i >= 0] or [len(body)])
                g = next((g for p, g in marks if m.end() <= p < end), None)
            if g not in CLOSEUP_WORDS:
                out.append(w)
                break
    return out


def weak_camera_hit(body):
    """弱运镜：弱词后面 0–4 字内跟镜头动词，且同一分句里弱词前面 6 字内没有身体部位（“嘴角轻微下拉”是表演）；
    手持抖动类弱词要前面有“摄影机 / 镜头 / 机位”。"""
    for m in WEAK_MOVE_RE.finditer(body):
        a = max(body.rfind(c, 0, m.start()) for c in "，,。；;：:！!？?、\n") + 1
        if not WEAK_BODY_RE.search(body[max(a, m.start() - 6):m.start()]):
            return True
    return bool(WEAK_SHAKE_RE.search(body))


def far_near_gap(body):
    """同一镜正文里远处位置词在前、贴镜动作词在后，两者之间没有“拉远 / 后拉 / 逼近 / 推近 / 走到镜头前 / 大步走近”这类过渡时，
    返回 (远处词, 贴镜词)；贴镜在前、远处在后（人头掠出画后落幅停在远处的灯笼怪）不报。"""
    fars = [(m.start(), m.group(0)) for m in re.finditer("|".join(FAR_WORDS), body)]
    nears = [(m.start(), m.group(0)) for m in re.finditer("|".join(NEAR_CONTACT_WORDS), body)]
    for fp, fw in fars:
        for npos, nw in nears:
            if npos > fp and not FAR_NEAR_BRIDGE_RE.search(body[fp:npos]):
                return fw, nw
    return None


def key_occlusion_pair(sentences):
    """同一镜里关键动作句与整幅遮挡句相邻（序号差 ≤1）时返回 (动作词, 遮挡词)；两句各带第N秒且相差 ≥1 秒视为已错开。"""
    def keys(s):
        t = KEY_ACTION_SKIP_RE.sub("", s)
        return [m.group(0) for rx in KEY_ACTION_RES for m in [rx.search(t)] if m]
    def occs(s):
        return [m.group(0) for m in FULL_OCCLUSION_RE.finditer(s)
                if not OCCLUSION_NEGATION_RE.search(s[max(0, m.start() - 2):m.start()])]
    def anchor(s):
        m = SECOND_ANCHOR_RE.search(s)
        return float(m.group(1)) if m else None
    K, O = [keys(s) for s in sentences], [occs(s) for s in sentences]
    for i, ks in enumerate(K):
        if not ks:
            continue
        for j in (i - 1, i, i + 1):
            if 0 <= j < len(sentences) and O[j]:
                a, b = anchor(sentences[i]), anchor(sentences[j])
                if i != j and a is not None and b is not None and abs(a - b) >= 1:
                    continue
                return ks[0], O[j][0]
    return None


def force_process_hits(sentence):
    """一句里的发力过程写法。重心类（重心移到左脚）单独出现不报；同句已有其它发力过程词，或同句写了转肩 / 转胯 / 力……传到
    （FORCE_CHAIN_TRIGGER_RE）时一起列出——只有传力类触发时它本身归机制词，由调用处并成“同句机制词”。"""
    hits = [m.group(0) for rx in FORCE_PROCESS_RES for m in rx.finditer(sentence)]
    chain = [m.group(0) for m in FORCE_CHAIN_ONLY_RE.finditer(sentence)]
    trig = [m.group(0) for m in FORCE_CHAIN_TRIGGER_RE.finditer(sentence)] if chain else []
    if chain and (hits or trig):
        if not hits:
            hits = [t for t in trig if not re.search(r"[传力劲]", t)]
        hits += chain
    return list(dict.fromkeys(hits))


def subject_action_hits(sentence):
    """主体段一句里的动作、表演、情绪、随动、持物状态与调度词（先挖掉“不采用……”排除分句）。
    返回 (词列表, 其中的持物词, 其中的情绪词)；同句写明“不换手 / 不离手 / 不离身”或“全程 / 一直 + 左手 / 右手 + 握……”的持物不报
    （全片不换手的道具归属是身份层面的事实）。"""
    s = SUBJECT_SKIP_RE.sub("", sentence)
    # 素材绑定句（有素材标签又有绑定动词）里的机位、构图、景别是这份素材负责的范围，不算调度；持物与动作照报
    binding = bool(LABEL_RE.search(s)) and any(v in s for v in BIND_VERBS)
    fixed = bool(PROP_FIXED_RE.search(s))
    s = PROP_FIXED_RE.sub("", s)
    hold = [] if fixed else [m.group(0) for m in SUBJECT_PROP_RE.finditer(s)]
    rxs = (SUBJECT_PROP_CHANGE_RE, SUBJECT_FOLLOW_RE, SUBJECT_ACTION_RE) + (() if binding else (SUBJECT_CAMERA_RE,))
    emotion = [m.group(0) for m in SUBJECT_EMOTION_RE.finditer(s)]
    hits = hold + [m.group(0) for rx in rxs for m in rx.finditer(s)] + emotion
    return list(dict.fromkeys(hits)), hold, emotion


def framing_clause(text, start, end):
    """强档命中所在的分句是镜内的取景约束：点名的部位就是这一分句的主语（“头部和双肩始终留在画内”；
    “那颗被它双手捧着的人头”“腰间的人头”里的部位只是修饰，不算），或分句里有画框切线词。"""
    a = max(text.rfind(c, 0, start) for c in "，,。；;：:！!？?\n") + 1
    b = min([i for i in (text.find(c, end) for c in "，,。；;！!？?\n") if i >= 0] or [len(text)])
    return bool(FRAME_SUBJECT_RE.search(text[a:start]) or FRAME_CUT_RE.search(text[a:b]))


def scene_env_clause(text, start):
    """场景段里强档命中词前面的分句说的是雨、雪、风、雾、烟、光、灯、火、云，而且不是人物或角色：环境句（成文主规则第 7 条⑤）。"""
    a = max(text.rfind(c, 0, start) for c in "，,。；;：:！!？?\n") + 1
    head = text[a:start]
    return bool(SCENE_ENV_SUBJECT_RE.search(head)) and not SCENE_NOT_ENV_RE.search(head)


def strong_guarantee_hits(sentence, in_shot=False, in_scene=False):
    """强档：一句里的总括保证词。只有镜头正文里的普通句（in_shot=True）才看取景豁免；场景段（in_scene=True）里主语是
    雨、雪、风、雾、烟、光、灯、火、云的环境句不报；主体段、风格段和镜内以“整段里 / 全片”开头的总览句不豁免。"""
    out = []
    for m in GUARANTEE_STRONG_RE.finditer(sentence):
        w = m.group(0)
        if in_shot and not GUARANTEE_ALWAYS_RE.search(w) and framing_clause(sentence, m.start(), m.end()):
            continue
        if in_scene and not GUARANTEE_ALWAYS_RE.search(w) and scene_env_clause(sentence, m.start()):
            continue
        out.append(w)
    return list(dict.fromkeys(out))


def position_guarantee_hits(sentence):
    """站位保证（左右 / 位置 / 站位 / 相对位置 + 全程 / 始终 / 一直 + 不变 / 保持）：全稿各段都扫、不给取景豁免；
    “它在画面里的大小和位置始终不变”说的是被拍主体在画框里的大小和位置（跟拍取景），不算。"""
    out = []
    for m in POSITION_GUARANTEE_RE.finditer(sentence):
        a = max(sentence.rfind(c, 0, m.start()) for c in "，,。；;：:！!？?\n") + 1
        if POSITION_FRAME_RE.search(sentence[a:m.start()]):
            continue
        # 只说一个被拍主体停在画面哪里（“灯笼的位置一直保持在画面左上”）是它在画框里的位置，不是两人站位
        if ((m.group("k1") or m.group("k2")) == "位置" and POSITION_FRAME_AFTER_RE.search(sentence[m.end():])
                and not POSITION_PLURAL_RE.search(sentence[a:m.end()])):
            continue
        out.append(m.group(0))
    return list(dict.fromkeys(out))


def broad_guarantee_hits(sentence, in_shot=False):
    """宽档：一句里的“始终 / 一直 / 全程 / 持续……”，所在分句有数量锁、身份锁、全片不换手的道具归属、镜头性格、
    伤势与外形状态就不算。取景豁免（点名部位或切线）只给镜头正文里的普通句（in_shot=True）；宽档扫的主体段和
    镜内总览句都不是，所以主体段的“两人的左右位置全程不变”“灯笼怪的全身始终留在画面里”照报。"""
    out = []
    for clause in re.split(r"[，,：:]", sentence):
        if GUARANTEE_EXEMPT_RE.search(clause):
            continue
        if in_shot and (FRAME_CUT_RE.search(clause) or (FRAME_PART_RE.search(clause) and re.search(r"画内|画面|画框", clause))):
            continue
        out += [m.group(0) for m in GUARANTEE_BROAD_RE.finditer(clause)]
    return list(dict.fromkeys(out))


def scene_activity_hits(sentence):
    """场景段一句里的角色活动：角色类背景群体名词后面跟着活动动词（天气与环境反应不在名词表里）。"""
    s = SUBJECT_SKIP_RE.sub("", sentence)
    g = SCENE_GROUP_RE.search(s)
    if not g:
        return []
    acts = [m.group(0) for m in SCENE_ACT_RE.finditer(s, g.start())]
    return list(dict.fromkeys([g.group(0)] + acts)) if acts else []


def shot_key(h):
    """认同一镜：有镜号按镜号，“a-b秒：”这类没有镜号的标题按时码。"""
    return h[2] if h[2] is not None else (h[3], h[4])


def shot_text(h, body_lines):
    """一镜的正文：去掉镜头标题本身，台词还在（调用处按需要去掉）。"""
    body = "\n".join(body_lines)
    hm = HEAD_PATTERNS[h[1]].match(body)
    return body[hm.end():] if hm else body


def repeat_segments(body, drop=()):
    """复读扫描用的一镜片段：去掉说话人前缀、台词、音效 <…>、每镜照写的固定句和 drop 里的文字（锁定文字、点名的否定句），
    再按标点与空白切成只含字与数字的片段。"""
    t = SPEAKER_PREFIX_RE.sub("\n", body)
    t = DIALOGUE_RE.sub("\n", t)
    t = SOUND_MARK_RE.sub("\n", t)
    t = REPEAT_FIXED_RE.sub("\n", t)
    for d in sorted((x for x in drop if x.strip()), key=len, reverse=True):
        t = t.replace(d, "\n")
    return re.findall(r"[^\W_]+", t)


def repeat_masks(segs, fixed_grams, w=REPEAT_WINDOW):
    """每个片段逐字标出不算内容的位置：结构词（画框切线、画面坐标与大小、运镜景别机位、时间点、素材短名）和主体段、场景段里
    也有的 w 字窗口。在片段上下文里算，免得“画面左侧的那半边脸”“画面右侧的那半边脸”分岔后剩下的“侧的那半边脸”被当成内容。"""
    masks = []
    for s in segs:
        mask = [False] * len(s)
        spans = [m.span() for m in REPEAT_STRUCT_RE.finditer(s)]
        spans += [(i, i + w) for i in range(len(s) - w + 1) if s[i:i + w] in fixed_grams]
        for a, b in spans:
            mask[a:b] = [True] * (b - a)
        masks.append(mask)
    return masks


def repeat_core_len(seg, mask, start, end):
    """片段 seg 里 [start, end) 这一处短语还剩几个内容字：去掉掩码位置，两头的虚字和量词也不算。"""
    idx = [i for i in range(start, end) if not mask[i]]
    while idx and seg[idx[0]] in REPEAT_EDGE_CHARS:
        idx.pop(0)
    while idx and seg[idx[-1]] in REPEAT_EDGE_CHARS:
        idx.pop()
    return len(idx)


def repeat_phrases(segs, fixed_grams, w=REPEAT_WINDOW):
    """复读（成文主规则第 5 条）：segs 是按出现先后排好的片段。连续 w 个字的窗口全稿出现 ≥2 次（主体段、场景段里也有的窗口不算；
    同一片段里互相重叠的两处不算），每对出现位置向两边扩到不再相同，得到最长公共短语。返回 [(短语, 次数)]，按首次出现先后排：
    含素材短名的整条不报；每一处出现都去掉结构词、主体段与场景段也有的窗口、两头的虚字，剩下不足 w 个字的不报；
    被更长的入选短语包含的只留长的。"""
    idx = {}
    for s in segs:
        for i in range(len(s) - w + 1):
            g = s[i:i + w]
            if g not in fixed_grams:
                occ = idx.setdefault(g, {})
                occ[(s, i)] = occ.get((s, i), 0) + 1
    found = set()
    for occ in idx.values():
        if sum(occ.values()) < 2:
            continue
        keys = list(occ)
        found.update(a for (a, _i), c in occ.items() if c >= 2)   # 两处片段一字不差：整段就是公共短语
        for x, (a, ia) in enumerate(keys):
            for b, ib in keys[x + 1:]:
                if a == b and abs(ia - ib) < w:
                    continue
                left = 0
                while ia - left > 0 and ib - left > 0 and a[ia - left - 1] == b[ib - left - 1]:
                    left += 1
                right = w
                while ia + right < len(a) and ib + right < len(b) and a[ia + right] == b[ib + right]:
                    right += 1
                found.add(a[ia - left:ia + right])
    masks = repeat_masks(segs, fixed_grams, w)
    counted = []
    for ph in found:
        where = [(k, m.start()) for k, s in enumerate(segs) for m in re.finditer(re.escape(ph), s)]
        n = sum(s.count(ph) for s in segs)
        if n < 2 or LABEL_RE.search(ph):
            continue
        core = min(repeat_core_len(segs[k], masks[k], i, i + len(ph)) for k, i in where)
        if core >= w:
            counted.append((ph, n))
    keep = []
    for ph, n in sorted(counted, key=lambda x: (-len(x[0]), x[0])):
        if not any(ph in k for k, _n in keep):
            keep.append((ph, n))
    first = {ph: next(k for k, s in enumerate(segs) if ph in s) for ph, _n in keep}
    return sorted(keep, key=lambda x: (first[x[0]], segs[first[x[0]]].find(x[0])))


