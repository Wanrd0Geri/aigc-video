def cjk_to_int(s):
    if s.isdigit():
        return int(s)
    if s == "十":
        return 10
    if "十" in s:
        a, b = s.split("十", 1)
        return (CJK_MAP.get(a, 1) if a else 1) * 10 + (CJK_MAP.get(b, 0) if b else 0)
    return CJK_MAP.get(s, 0)


